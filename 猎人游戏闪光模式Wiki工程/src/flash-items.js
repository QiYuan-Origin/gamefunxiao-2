function escapeHtml(value) {
  return String(value)
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;')
    .replaceAll("'", '&#39;');
}

function renderRows(rows) {
  return rows.map(row => `
    <tr>
      <td><b>${escapeHtml(row[0])}</b></td>
      <td>${escapeHtml(row[1])}</td>
      <td>${escapeHtml(row[2])}</td>
      <td>${escapeHtml(row[3])}</td>
    </tr>
  `).join('');
}

function renderNotes(notes) {
  if (!notes || notes.length === 0) {
    return '';
  }
  return `<div class="wiki-notice note"><b>注意：</b><ul>${notes.map(note => `<li>${escapeHtml(note)}</li>`).join('')}</ul></div>`;
}

function createFishingName(id) {
  const index = id - 1;
  return FISHING_PREFIXES[index % FISHING_PREFIXES.length]
    + FISHING_CORES[Math.floor(index / FISHING_PREFIXES.length) % FISHING_CORES.length]
    + '·'
    + FISHING_SUFFIXES[Math.floor(index / (FISHING_PREFIXES.length * FISHING_CORES.length)) % FISHING_SUFFIXES.length];
}

function renderFishingRows() {
  return Array.from({ length: 300 }, (_, index) => {
    const id = index + 1;
    const material = FISHING_MATERIALS[index % FISHING_MATERIALS.length];
    return `
      <tr>
        <td>${String(id).padStart(3, '0')}</td>
        <td>${escapeHtml(createFishingName(id))}</td>
        <td><code>minecraft:${material[0]}</code><br><small>${material[1]}</small></td>
        <td>${FISHING_TRAPS[index % FISHING_TRAPS.length]}</td>
      </tr>
    `;
  }).join('');
}

