const FLASH_GUIDE_PAGES = [
  flashOverviewPage,
  flashMatchFlowPage,
  flashHunterPage,
  flashPreyPage,
  flashControlsPage,
  flashLoadoutPage
];

function belongsToFlashWiki(page) {
  return page?.group?.startsWith('闪光模式')
    || page?.categories?.includes('闪光模式')
    || page?.slug === 'hunter-end-flash';
}

export function installFlashGuidePages(pages) {
  if (!Array.isArray(pages)) {
    return;
  }

  for (const page of pages) {
    if (belongsToFlashWiki(page)) {
      page.version = FLASH_WIKI_VERSION;
    }
  }

  let insertAt = pages.findIndex(page => page.slug === 'flash');
  if (insertAt < 0) {
    insertAt = pages.length;
  }

  for (const guidePage of FLASH_GUIDE_PAGES) {
    const existingIndex = pages.findIndex(page => page.slug === guidePage.slug);
    if (existingIndex >= 0) {
      pages[existingIndex] = guidePage;
      insertAt = existingIndex;
      continue;
    }
    insertAt += 1;
    pages.splice(insertAt, 0, guidePage);
  }
}
